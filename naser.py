def spread_per_day(n, start=9*60, end=22*60):
    n = max(1, min(int(n), 14))
    if n == 1: return ["12:00"]
    step = (end - start) / (n - 1)
    return [f"{int(round(start + i*step))//60:02d}:{int(round(start + i*step))%60:02d}" for i in range(n)]

def extract_json(txt):
    if not txt: return None
    txt = re.sub(r"<think>.*?</think>", "", txt, flags=re.S)
    m = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", txt, re.S)
    cand = m.group(1) if m else None
    if not cand:
        s = txt.find("{"); e = txt.rfind("}")
        if s == -1 or e <= s: return None
        cand = txt[s:e+1]
    try: return json.loads(cand)
    except Exception:
        try: return json.loads(re.sub(r",\s*([}\]])", r"\1", cand))
        except Exception: return None

